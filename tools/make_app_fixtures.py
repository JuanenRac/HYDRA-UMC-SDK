"""Writes `conformance/app-fixtures/v1/server-answers.json`: for every route of the full server inventory that names the
shape of its answer, one `minimal` body (only the required fields) and one `full` body (every declared field), built from
the shape and nothing else. An app (Android, iOS, the Pi kiosk, the Studio) replays these answers against its own models,
so a single description of the server's answers, the OpenAPI inventory, is what every client is tested with.

    python tools/make_app_fixtures.py            write the file
    python tools/make_app_fixtures.py --check    fail when the file is not what the inventory produces

Read-only with `--check`. Standard library only.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
INVENTORY = ROOT / "contracts" / "openapi" / "v1" / "server.full.openapi.json"
OUTPUT = ROOT / "conformance" / "app-fixtures" / "v1" / "server-answers.json"
METHODS = ("get", "post", "put", "patch", "delete")
MAX_DEPTH = 8


def _resolve(ref: str, doc: dict[str, Any]) -> dict[str, Any]:
    node: Any = doc
    for part in ref.lstrip("#/").split("/"):
        node = node[part.replace("~1", "/").replace("~0", "~")]
    return node


def sample(schema: Any, doc: dict[str, Any], full: bool, depth: int = 0) -> Any:
    """A value that satisfies `schema`: with `full` every declared property, otherwise only the required ones."""
    if not isinstance(schema, dict) or depth > MAX_DEPTH:
        return None
    if "$ref" in schema:
        return sample(_resolve(schema["$ref"], doc), doc, full, depth + 1)
    for key in ("example", "default", "const"):
        if key in schema:
            return schema[key]
    if schema.get("enum"):
        return schema["enum"][0]
    if schema.get("allOf"):
        merged: dict[str, Any] = {}
        for part in schema["allOf"]:
            value = sample(part, doc, full, depth + 1)
            if isinstance(value, dict):
                merged.update(value)
        return merged
    for key in ("oneOf", "anyOf"):
        if schema.get(key):
            return sample(schema[key][0], doc, full, depth + 1)
    kind = schema.get("type")
    if isinstance(kind, list):
        kind = next((k for k in kind if k != "null"), "null")
    if kind == "object" or (kind is None and "properties" in schema):
        properties = schema.get("properties", {})
        names = list(properties) if full else list(schema.get("required", []))
        return {name: sample(properties.get(name, {}), doc, full, depth + 1) for name in names}
    if kind == "array":
        count = max(int(schema.get("minItems", 0)), 1 if full else 0)
        return [sample(schema.get("items", {}), doc, full, depth + 1) for _ in range(count)]
    if kind == "string":
        text = {"date-time": "2026-01-01T00:00:00Z", "date": "2026-01-01", "uri": "http://localhost/",
                "uuid": "00000000-0000-4000-8000-000000000000"}.get(schema.get("format"), "sample")
        return text[: schema["maxLength"]] if "maxLength" in schema else text
    if kind == "integer":
        return int(schema.get("minimum", 0))
    if kind == "number":
        return float(schema.get("minimum", 0))
    if kind == "boolean":
        return False
    return None


def build(doc: dict[str, Any]) -> dict[str, Any]:
    routes: dict[str, Any] = {}
    for path in sorted(doc["paths"]):
        for method in METHODS:
            operation = doc["paths"][path].get(method)
            if not operation:
                continue
            answers: dict[str, Any] = {}
            for status in sorted(operation.get("responses", {})):
                schema = operation["responses"][status].get("content", {}).get("application/json", {}).get("schema")
                if schema is None:
                    continue
                answers[status] = {"minimal": sample(schema, doc, False), "full": sample(schema, doc, True)}
            if answers:
                routes[f"{method.upper()} {path}"] = answers
    return {
        "description": "Answers of HYDRA-UMC-SERVER built from the shapes of contracts/openapi/v1/server.full.openapi.json; generated by tools/make_app_fixtures.py, never edited by hand.",
        "routes": routes,
    }


def render(doc: dict[str, Any]) -> str:
    return json.dumps(build(doc), indent=2, ensure_ascii=False, sort_keys=False) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail when the file differs from what the inventory produces")
    args = parser.parse_args(argv)
    text = render(json.loads(INVENTORY.read_text(encoding="utf-8")))
    if args.check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.is_file() else ""
        if current != text:
            print(f"FAIL: {OUTPUT.relative_to(ROOT)} is not what the inventory produces; run python tools/make_app_fixtures.py", file=sys.stderr)
            return 1
        print(f"PASS: {OUTPUT.relative_to(ROOT)} follows the inventory ({len(json.loads(text)['routes'])} routes)")
        return 0
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    with OUTPUT.open("w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)
    print(f"wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
