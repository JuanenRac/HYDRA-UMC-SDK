"""One registry of the services of the ecosystem: port, health path and systemd unit.

`contracts/ports.yaml` is generated from what each repository already declares: the `service` block of its
`hydra-umc.project.json` and, when the manifest has no port, the `--port N` of its systemd unit. `--check`
writes nothing and fails when

* the registry differs from what the repositories declare,
* two services share a port,
* a manifest port differs from the port in the repository's own systemd unit,
* a unit named by a manifest has no file in the repository's `systemd/` folder, or
* an installer of HYDRA-UMC-OS (`provisioning/install_*.sh`) names a unit that no manifest declares.

    python tools/sync_ports.py --check
    python tools/sync_ports.py             # rewrite contracts/ports.yaml
    python tools/sync_ports.py --workspace DIR
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

SDK_ROOT = Path(__file__).resolve().parents[1]
REGISTRY = SDK_ROOT / "contracts" / "ports.yaml"
HEADER = (
    "# Generated by tools/sync_ports.py from the `service` block of each hydra-umc.project.json and the\n"
    "# `--port` of its systemd unit. Do not edit by hand: run `python tools/sync_ports.py`.\n"
)
_UNIT_PORT = re.compile(r"--port[ =](\d+)|\bPORT=(\d+)")
_UNIT_NAME = re.compile(r"\bhydra-umc-[a-z0-9-]+\.service\b")
# units an installer may name without them being a service of a repository of the family
_NOT_SERVICES = frozenset()


def _read(path: Path) -> str:
    return path.read_text(encoding="utf-8", errors="replace")


def unit_port(repo: Path, unit: str | None) -> int | None:
    if not unit:
        return None
    path = repo / "systemd" / unit
    if not path.is_file():
        return None
    found = [int(a or b) for a, b in _UNIT_PORT.findall(_read(path))]
    return found[0] if found else None


def collect(workspace: Path) -> tuple[list[dict], list[str]]:
    """(services sorted by name, problems found while reading them)."""
    services: list[dict] = []
    problems: list[str] = []
    for manifest in sorted(workspace.glob("HYDRA-UMC*/hydra-umc.project.json")):
        repo = manifest.parent
        try:
            data = json.loads(_read(manifest))
        except ValueError:
            problems.append(f"{repo.name}: manifest is not valid JSON")
            continue
        service = data.get("service")
        if not isinstance(service, dict):
            continue
        unit = service.get("systemd_unit")
        declared = service.get("port")
        from_unit = unit_port(repo, unit)
        if unit and not (repo / "systemd" / unit).is_file():
            problems.append(f"{repo.name}: unit {unit} has no file in systemd/")
        if declared is not None and from_unit is not None and declared != from_unit:
            problems.append(f"{repo.name}: manifest port {declared} differs from the port {from_unit} of {unit}")
        port = declared if declared is not None else from_unit
        services.append({
            "name": data.get("name", repo.name),
            "port": port,
            "health_path": service.get("health_path"),
            "systemd_unit": unit,
        })
    owners: dict[int, list[str]] = {}
    for item in services:
        if item["port"] is not None:
            owners.setdefault(item["port"], []).append(item["name"])
    for port, names in sorted(owners.items()):
        if len(names) > 1:
            problems.append(f"port {port} is used by {', '.join(names)}")
    return services, problems


def installer_problems(workspace: Path, services: list[dict]) -> list[str]:
    known = {item["systemd_unit"] for item in services if item["systemd_unit"]}
    # a unit that a repository ships (a timer's oneshot, or a service whose manifest has no `service` block)
    known |= {path.name for path in workspace.glob("HYDRA-UMC*/systemd/*.service")}
    problems: list[str] = []
    folder = workspace / "HYDRA-UMC-OS" / "provisioning"
    for script in sorted(folder.glob("install_*.sh")) if folder.is_dir() else []:
        for line in _read(script).splitlines():
            if line.lstrip().startswith("#"):
                continue
            for unit in _UNIT_NAME.findall(line):
                if unit not in known and unit not in _NOT_SERVICES and not (script.parent.parent / "systemd" / unit).is_file():
                    problems.append(f"{script.name}: names {unit}, which no repository declares")
    return sorted(set(problems))


def render(services: list[dict]) -> str:
    lines = [HEADER.rstrip("\n"), "services:"]
    for item in services:
        lines.append(f"  - name: {item['name']}")
        for key in ("port", "health_path", "systemd_unit"):
            value = item[key]
            lines.append(f"    {key}: {'null' if value is None else value}")
    return "\n".join(lines) + "\n"


def parse(text: str) -> list[dict]:
    """Reads back what `render` writes (a list of flat mappings), without a YAML library."""
    items: list[dict] = []
    for raw in text.splitlines():
        line = raw.rstrip()
        if not line or line.lstrip().startswith("#") or line == "services:":
            continue
        key, _, value = line.strip().lstrip("- ").partition(": ")
        value = value.strip()
        if line.lstrip().startswith("- "):
            items.append({})
        parsed = None if value == "null" else int(value) if value.isdigit() else value
        items[-1][key] = parsed
    return items


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="write nothing; exit 1 on any problem")
    parser.add_argument("--workspace", type=Path, default=SDK_ROOT.parent)
    parser.add_argument("--registry", type=Path, default=REGISTRY)
    args = parser.parse_args(argv)
    workspace = args.workspace.resolve()
    services, problems = collect(workspace)
    problems += installer_problems(workspace, services)
    wanted = render(services)
    if args.check:
        current = args.registry.read_text(encoding="utf-8").replace("\r\n", "\n") if args.registry.is_file() else ""
        if current != wanted:
            problems.append(f"{args.registry.name} is out of date; run python tools/sync_ports.py")
        for line in problems:
            print("PORTS: " + line)
        print(f"PORTS={'FAIL' if problems else 'PASS'} services={len(services)} problems={len(problems)}")
        return 1 if problems else 0
    args.registry.parent.mkdir(parents=True, exist_ok=True)
    args.registry.write_bytes(wanted.encode("utf-8"))
    for line in problems:
        print("PORTS: " + line)
    print(f"PORTS=WRITTEN services={len(services)} problems={len(problems)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
